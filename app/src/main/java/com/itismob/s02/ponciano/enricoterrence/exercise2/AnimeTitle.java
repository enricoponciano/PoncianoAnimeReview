package com.itismob.s02.ponciano.enricoterrence.exercise2;
public class AnimeTitle {
    private int imageId;
    private String name;

    public AnimeTitle(int imageId, String name) {
        this.imageId = imageId;
        this.name = name;
    }

    public int getImageId() {
        return this.imageId;
    }

    public String getName() {
        return this.name;
    }
}